#!/bin/bash
# cbmPkgScaffold.sh --- copy the generic skeleton of a bisos-pip CBM package into a new, initiated repo.
#
# Usage:  cbmPkgScaffold.sh <name> [modelName]
#   <name>       the new package's short name (bisos.<name>), e.g. prometheus. Run from anywhere.
#   [modelName]  the package copied from (default kafka); must be under /bisos/git/bxRepos/bisos-pip/.
#
# Copies only what does not depend on the program being packaged: the fto/tree markers, the py3/
# packaging files, the namespace __init__, and the panel tree. Every occurrence of the model's name is
# replaced (lower case and Capitalized). The program-specific files --- <name>Info.py, the sboms, the
# units, dns/wvd/assemble, cbs/cbm, <name>Admin.cs, quick<Name>.cs, README.org, tests --- are written
# by hand afterwards; see SKILL.md. Refuses to overwrite a file that exists.
#
# Precondition: the repo exists (git clone of the empty GitHub repo) and aiActivity.cs -i initiate
# --activity=bisos-pip has been run in it.

set -e
name="$1"; model="${2:-kafka}"
[ -n "$name" ] || { echo "usage: $0 <name> [modelName]" >&2; exit 1; }
base=/bisos/git/bxRepos/bisos-pip
src="$base/$model"; dst="$base/$name"
[ -d "$src" ] || { echo "no model package at $src" >&2; exit 1; }
[ -d "$dst/.git" ] || { echo "$dst is not a git repo" >&2; exit 1; }

Model="$(tr '[:lower:]' '[:upper:]' <<< "${model:0:1}")${model:1}"
Name="$(tr '[:lower:]' '[:upper:]' <<< "${name:0:1}")${name:1}"

files=(
    _objectType_ _treeProc_ _tree_ ftoProc.sh
    py3/.gitattributes py3/.gitignore py3/_objectType_ py3/_treeProc_ py3/_tree_ py3/ftoProc.sh
    py3/lh-agpl3-LICENSE.txt py3/pypiProc.sh py3/pyproject.toml py3/setup.py
    py3/bisos/__init__.py
)
# The panel tree: the model's tracked files, or its files on disk if it is not committed yet.
panelFiles() {
    ( cd "$src" && { git ls-files "py3/panels/bisos.$model" | grep . || \
                     find "py3/panels/bisos.$model" \( -type f -o -type l \) | sort ; } )
}
while IFS= read -r f ; do files+=("$f") ; done < <(panelFiles | grep -v '/README/fullUsagePanel-en.org$')

for f in "${files[@]}" ; do
    t="${f//bisos.$model/bisos.$name}"
    [ -e "$dst/$t" ] && { echo "exists, left alone: $t" ; continue ; }
    mkdir -p "$(dirname "$dst/$t")"
    sed -e "s/$model/$name/g" -e "s/$Model/$Name/g" "$src/$f" > "$dst/$t"
    [ -x "$src/$f" ] && chmod +x "$dst/$t"
    echo "copied: $t"
done

# The panel's terseTreeNavigator body is generated by Blee; the model's child panels do not exist here.
nodeBase="$dst/py3/panels/bisos.$name/_nodeBase_/fullUsagePanel-en.org"
[ -f "$nodeBase" ] && sed -i '/^\*   =Decedents=/d' "$nodeBase"

mkdir -p "$dst/py3/bisos/$name" "$dst/py3/bin" "$dst/py3/tests" "$dst/tests"
[ -e "$dst/py3/bisos/$name/__init__.py" ] || : > "$dst/py3/bisos/$name/__init__.py"
# The README panel is the repo's README.org, by symlink.
ln -sfn ../../../../README.org "$dst/py3/panels/bisos.$name/README/fullUsagePanel-en.org"
echo "scaffolded $dst from $src. Next: the hand-written files (SKILL.md, 'Files to write')."
